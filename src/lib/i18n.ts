import { AppLanguage, WORLD_LANGUAGES } from '../types/chat';

const WORLD_LANG_CODES = new Set<string>(WORLD_LANGUAGES.map((l) => l.code));

export function normalizeAppLanguage(code: string | null | undefined): AppLanguage {
  if (code && WORLD_LANG_CODES.has(code)) {
    return code as AppLanguage;
  }
  return 'en';
}

export function isRtlLanguage(lang: AppLanguage): boolean {
  const entry = WORLD_LANGUAGES.find((l) => l.code === lang);
  return Boolean(entry?.rtl);
}

